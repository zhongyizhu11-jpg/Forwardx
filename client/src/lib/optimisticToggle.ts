/**
 * 乐观开关跑完一轮之后，该显示哪个值。
 *
 * 答案是**外部值**——也就是服务端落成的那个，而不是我们刚发出去的那个。
 *
 * 原来这里有个隐含假设：「请求什么，服务端就会变成什么」。于是队列跑完时只在
 * `外部值 === 刚发的值` 的时候才回同步，两者不一致就继续显示刚发的值。可这种不一致
 * 恰恰是最需要说出来的情形 —— 比如给一个超额的用户开「转发」：服务端记下了意图，
 * 但重算后生效值仍然是关。开关却一直亮着，刷新前谁也看不出来。
 *
 * 这条规则本身一行就能写完，单独摆出来是为了能被断言：它是个**假设**，而假设写在
 * 一个 finally 分支的条件里，没人会发现它错了。
 */
export function settledToggleChecked(externalChecked: boolean, lastSentChecked: boolean): boolean {
  // lastSentChecked 只用来表达「我们请求过什么」，不参与判断 —— 留着参数是为了
  // 让调用处读起来清楚：这一步就是拿外部值把请求值覆盖掉。
  void lastSentChecked;
  return externalChecked;
}
